import { waitForAsync } from "./helpers/wait-async.mjs";
import assert from "node:assert/strict";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import { staticServer } from "../dev/server.mjs";

const { chromium } = await import(process.env.MIACODE_PLAYWRIGHT_MODULE ? pathToFileURL(process.env.MIACODE_PLAYWRIGHT_MODULE).href : "playwright");
const output = resolve("artifacts/document"); mkdirSync(output, { recursive: true });
const server = staticServer(process.cwd(), { performanceTerminal: false });
await new Promise(resolve => server.listen(0, "127.0.0.1", resolve));
const browser = await chromium.launch({ headless: true });
try {
  const page = await browser.newPage({ viewport: { width: 1600, height: 900 } });
  const errors = []; page.on("pageerror", error => errors.push(error.message));
  await page.goto(`http://127.0.0.1:${server.address().port}/index.html`);
  await page.locator(".welcome-title").waitFor();
  await page.evaluate(() => document.getElementById("workbench").editor.ready);
  const source = "&title=文档测试\n&artist=Team MiaCode\n&first=-0.125\n&clock_count=6\n&custom_field=保留字段\n&des_7=独立名义\n&lv_5=12\n&inote_5=(120){4}1,2,3,E\n&lv_6=13\n&inote_6=(120){4}4,5,6,E\n";
  await page.evaluate(source => document.getElementById("workbench").editor.load({ maidata: source }, "Song/maidata.txt"), source);
  const getDocument = () => page.evaluate(() => document.getElementById("workbench").editor.preview.getDocument());
  const opened = await getDocument();
  assert.equal(opened.activeDifficultyId, 5);
  assert.equal(opened.filePath, "Song/maidata.txt");
  assert.equal(opened.metadataClockCount, "6");
  assert.equal(opened.currentDifficultyOffset, "-0.125");
  assert.equal(opened.currentDifficultyLevel, "12");
  assert.equal(opened.designerSlots.find(slot => slot.id === 7).hasChart, false);
  assert.equal(opened.designerSlots.find(slot => slot.id === 7).designer, "独立名义");
  assert.equal(await page.getByRole("textbox", { name: "Simai 谱面正文", exact: true }).inputValue(), "(120){4}1,2,3,E");
  assert.match(opened.sourceText, /&custom_field=保留字段/);
  await page.evaluate(() => {
    globalThis.documentChanges = [];
    document.getElementById("workbench").editor.preview.on("documentChanged", snapshot => documentChanges.push(snapshot));
  });
  const initialState = await page.evaluate(() => document.getElementById("workbench").editor.preview.getState());
  assert.equal(initialState.statisticsAvailable, true);
  assert.deepEqual(initialState.statistics.find(item => item.kind === "total"), { kind: "total", played: 1, total: 3, value: "1/3" });
  assert.equal(await page.locator('.note-stat-cell[data-kind="total"] .note-stat-value').textContent(), "1/3");
  await page.evaluate(() => document.getElementById("workbench").editor.preview.seek(1));
  await page.waitForFunction(() => document.querySelector('.note-stat-cell[data-kind="total"] .note-stat-value').textContent === "3/3");
  await page.evaluate(() => document.getElementById("workbench").editor.preview.seek(0));
  await page.waitForFunction(() => document.querySelector('.note-stat-cell[data-kind="total"] .note-stat-value').textContent === "1/3");
  const body = "(120){4}7,8,1,E";
  await page.getByRole("textbox", { name: "Simai 谱面正文", exact: true }).fill(body);
  await page.waitForFunction(() => document.getElementById("workbench").editor.workbench.documentSession.dirty);
  const edited = await getDocument();
  assert.equal(edited.chartText, body);
  assert.deepEqual(edited.dirtyDifficultyIds, [5]);
  assert.ok(edited.revision > opened.revision);
  await page.evaluate(() => document.getElementById("workbench").editor.command("document.metadataTitle", { value: "编辑后的标题" }));
  const metadata = await getDocument();
  assert.equal(metadata.metadataTitle, "编辑后的标题");
  assert.equal(metadata.metadataDirty, true);
  assert.equal(await page.evaluate(() => documentChanges.at(-1).metadataTitle), "编辑后的标题");
  const section = await page.evaluate(() => document.getElementById("workbench").editor.preview.getDocumentSaveText(5));
  assert.match(section.sourceText, /&title=文档测试/);
  assert.match(section.sourceText, /&inote_5=\(120\)\{4\}7,8,1,E/);
  assert.match(section.sourceText, /&inote_6=\(120\)\{4\}4,5,6,E/);
  assert.match(section.sourceText, /&custom_field=保留字段/);
  await page.evaluate(() => document.getElementById("workbench").editor.command("document.markSectionSaved", { section: 5 }));
  const saved = await getDocument();
  assert.deepEqual(saved.dirtyDifficultyIds, []);
  assert.equal(saved.dirty, true);
  assert.equal(saved.metadataDirty, true);
  await page.evaluate(() => document.getElementById("workbench").editor.command("document.selectDifficulty", { difficulty: 6 }));
  const selected = await getDocument();
  assert.equal(selected.activeDifficultyId, 6);
  assert.equal(selected.documentOpenGeneration, opened.documentOpenGeneration);
  assert.equal(selected.metadataTitle, "编辑后的标题");
  assert.equal(await page.getByRole("textbox", { name: "Simai 谱面正文", exact: true }).inputValue(), "(120){4}4,5,6,E");
  await page.getByRole("textbox", { name: "Simai 谱面正文", exact: true }).fill("(120){4}bad");
  await page.waitForFunction(() => document.getElementById("workbench").editor.workbench.documentSession.chartText === "(120){4}bad");
  assert.equal((await page.evaluate(() => document.getElementById("workbench").editor.preview.getState())).loaded, false);
  const invalidState = await page.evaluate(() => document.getElementById("workbench").editor.preview.getState());
  assert.equal(invalidState.statisticsAvailable, false);
  assert.deepEqual(invalidState.statistics, []);
  assert.equal(await page.locator('.note-stat-cell[data-kind="total"] .note-stat-value').textContent(), "—");
  assert.equal((await getDocument()).chartText, "(120){4}bad");
  await page.evaluate(() => document.getElementById("workbench").editor.command("document.selectDifficulty", { difficulty: 5 }));
  assert.equal((await getDocument()).activeDifficultyId, 5);
  assert.equal(await page.getByRole("textbox", { name: "Simai 谱面正文", exact: true }).inputValue(), body);
  await page.evaluate(() => document.getElementById("workbench").editor.command("document.selectDifficulty", { difficulty: 6 }));
  assert.equal(await page.getByRole("textbox", { name: "Simai 谱面正文", exact: true }).inputValue(), "(120){4}bad");
  await page.getByRole("textbox", { name: "Simai 谱面正文", exact: true }).fill("(120){4}5,6,7,E");
  await waitForAsync(page, async () => (await document.getElementById("workbench").editor.preview.getState()).loaded);
  const final = await getDocument();
  assert.equal(final.chartText, "(120){4}5,6,7,E");
  assert.match(final.sourceText, /&custom_field=保留字段/);
  assert.match(final.sourceText, /&des_7=独立名义/);
  await page.screenshot({ path: resolve(output, "document-editor.png") });
  assert.deepEqual(errors, []);
  writeFileSync(resolve(output, "results.json"), JSON.stringify({ browser: browser.version(), opened, edited, metadata, saved, selected, final, errors }, null, 2) + "\n");
  console.log("Native document ownership, body/metadata binding, section save, difficulty selection and invalid-text editing passed");
} finally {
  await browser.close(); server.closeAllConnections(); await new Promise(resolve => server.close(resolve));
}
