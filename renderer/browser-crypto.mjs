const rotateRight = (value, count) => (value >>> count) | (value << (32 - count));

export async function sha256Digest(input, provider = globalThis.crypto) {
  if (provider?.subtle) return provider.subtle.digest("SHA-256", input);
  const bytes = ArrayBuffer.isView(input)
    ? new Uint8Array(input.buffer, input.byteOffset, input.byteLength) : new Uint8Array(input);
  const state = new Uint32Array([0x6a09e667, 0xbb67ae85, 0x3c6ef372, 0xa54ff53a, 0x510e527f, 0x9b05688c, 0x1f83d9ab, 0x5be0cd19]);
  const words = new Uint32Array(64);
  function compress(view, offset) {
    for (let index = 0; index < 16; index++) words[index] = view.getUint32(offset + index * 4);
    for (let index = 16; index < 64; index++) {
      const first = words[index - 15], second = words[index - 2];
      const sigma0 = rotateRight(first, 7) ^ rotateRight(first, 18) ^ (first >>> 3);
      const sigma1 = rotateRight(second, 17) ^ rotateRight(second, 19) ^ (second >>> 10);
      words[index] = words[index - 16] + sigma0 + words[index - 7] + sigma1;
    }
    let [a, b, c, d, e, f, g, h] = state;
    for (let index = 0; index < 64; index++) {
      const sigma1 = rotateRight(e, 6) ^ rotateRight(e, 11) ^ rotateRight(e, 25);
      const choice = (e & f) ^ (~e & g);
      const temp1 = (h + sigma1 + choice + constants[index] + words[index]) >>> 0;
      const sigma0 = rotateRight(a, 2) ^ rotateRight(a, 13) ^ rotateRight(a, 22);
      const majority = (a & b) ^ (a & c) ^ (b & c);
      const temp2 = (sigma0 + majority) >>> 0;
      h = g;
      g = f;
      f = e;
      e = (d + temp1) >>> 0;
      d = c;
      c = b;
      b = a;
      a = (temp1 + temp2) >>> 0;
    }
    const next = [a, b, c, d, e, f, g, h];
    for (let index = 0; index < state.length; index++) state[index] += next[index];
  }
  const completeLength = bytes.length - bytes.length % 64;
  const view = new DataView(bytes.buffer, bytes.byteOffset, bytes.byteLength);
  for (let offset = 0; offset < completeLength; offset += 64) compress(view, offset);
  // Process padding in a bounded buffer instead of copying the runtime binary.
  const tail = new Uint8Array(bytes.length % 64 < 56 ? 64 : 128);
  tail.set(bytes.subarray(completeLength));
  tail[bytes.length % 64] = 0x80;
  const tailView = new DataView(tail.buffer);
  tailView.setUint32(tail.length - 8, Math.floor(bytes.length / 0x20000000));
  tailView.setUint32(tail.length - 4, bytes.length * 8);
  for (let offset = 0; offset < tail.length; offset += 64) compress(tailView, offset);
  const result = new DataView(new ArrayBuffer(32));
  for (let index = 0; index < state.length; index++) result.setUint32(index * 4, state[index]);
  return result.buffer;
}
